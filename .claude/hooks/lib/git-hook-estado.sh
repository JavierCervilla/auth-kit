# shellcheck shell=bash
# lib/git-hook-estado.sh — ¿corre el gate en git en este repo? Una sola respuesta (T-223, ronda 5).
#
# La usan las tres capas que antes decidían cada una por su cuenta y podían discrepar (ADV-T223-5):
# el instalador (`install-git-hooks.sh`, al instalar), su `--check`, y el PreToolUse
# (`commit_repo_nota_hookspath`/`_cr_gate_git` en `lib/commit-repo.sh`).
#
# Cuenta como instalado:
#   · nuestro shim (firma AGENTIC_GIT_HOOK) en `commit-msg`; o
#   · nuestro shim en `commit-msg.legacy` Y el `commit-msg` vigente es el hook de pre-commit, que es el que
#     ejecuta `.legacy` (migration mode de `pre-commit install -t commit-msg`). Si otra herramienta (el
#     hook Change-Id de Gerrit, por ejemplo) sobrescribe después `commit-msg`, nadie ejecuta `.legacy`: el
#     gate NO corre y cuenta como un commit-msg ajeno.
# Marca del hook de pre-commit (4.x, `pre_commit/resources/hook-tmpl`): la línea «# File generated by
# pre-commit» y la llamada a `hook-impl`, que es quien ejecuta el `.legacy`.

# agentic_hook_es_precommit <fichero> — ¿es el hook que genera pre-commit?
agentic_hook_es_precommit() {
  grep -qs '^# File generated by pre-commit' "$1" && grep -qs 'hook-impl' "$1"
}

# agentic_hook_instalado <dir-de-hooks> — 0 si el gate en git corre ahí (ver arriba), 1 si no.
# Un hook sin bit de ejecución no corre («hint: … hook was ignored because it's not set as executable»): con la
# firma sola contaba como instalado y el PreToolUse callaba (T-292 R3, ADV-T292-1). pre-commit tampoco ejecuta un
# `.legacy` sin +x.
agentic_hook_instalado() {
  [ -x "$1/commit-msg" ] || return 1
  grep -qs AGENTIC_GIT_HOOK "$1/commit-msg" && return 0
  grep -qs AGENTIC_GIT_HOOK "$1/commit-msg.legacy" && [ -x "$1/commit-msg.legacy" ] \
    && agentic_hook_es_precommit "$1/commit-msg" && return 0
  return 1
}
